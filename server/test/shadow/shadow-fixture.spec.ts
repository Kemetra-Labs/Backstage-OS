// COG-07 (BACK-110) shadow view fixture. The app's read-only shadow view reads a committed JSON file, never
// the server (cog-07-scope-decision.md). This spec keeps that file honest: it runs the real COG-03 search and
// COG-04 evaluator (with the independent validator) over the synthetic retrieval world and requires the
// committed file to equal the output. Regenerate with SHADOW_FIXTURE_WRITE=1 after an intended change.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { evaluate } from '../../src/reasoning/reasoning.evaluator';
import type { ReasoningInput } from '../../src/reasoning/reasoning.types';
import { validateResult } from '../../src/reasoning/reasoning.validator';
import { search } from '../../src/retrieval/retrieval.search';
import { GH, JIRA, REPO } from '../memory/memory.fixture';
import { world } from '../retrieval/retrieval.fixture';

const FIXTURE = resolve(process.cwd(), '..', 'app', 'src', 'fixture', 'shadow-cognition.json');

const QUERIES = ['login', 'BACK-7', '#12', 'سياسة الجلسة', 'payments outage'] as const;

const INPUT: ReasoningInput = {
  specVersion: 'shadow-demo-1',
  tasks: [
    {
      id: 'T1',
      task: { sourceId: JIRA, sourceRef: 'jira:BACK#issue/BACK-7', kind: 'jira_issue' },
      requirements: [
        { id: 'fix-merged', kind: 'check', target: { sourceId: GH, sourceRef: `${REPO}#pull/12`, kind: 'pull_request' }, expected: 'closed' },
        { id: 'owner-approval', kind: 'approval', expected: 'granted' },
      ],
    },
    {
      id: 'T2',
      task: { sourceId: JIRA, sourceRef: 'jira:BACK#issue/BACK-8', kind: 'jira_issue' },
      requirements: [{ id: 'after-T1', kind: 'dependency', target: { sourceId: JIRA, sourceRef: 'jira:BACK#issue/BACK-7', kind: 'jira_issue' }, expected: 'complete' }],
    },
    {
      id: 'T3',
      task: { sourceId: JIRA, sourceRef: 'jira:BACK#issue/BACK-99', kind: 'jira_issue' },
      requirements: [],
    },
  ],
};

function build() {
  const p = world();
  const reasoning = evaluate(p, INPUT);
  return {
    note: 'Synthetic shadow output of the Kawalys cognitive core (COG-03 search, COG-04 reasoning). Not live telemetry. Generated by server/test/shadow/shadow-fixture.spec.ts.',
    memoryPolicyVersion: p.policyVersion,
    retrievalPolicyVersion: search(p, QUERIES[0]).retrievalPolicyVersion,
    reasoningPolicyVersion: reasoning.reasoningPolicyVersion,
    searches: QUERIES.map((query) => {
      const r = search(p, query);
      return {
        query,
        outcome: r.outcome,
        totalMatches: r.totalMatches,
        hits: r.hits.map((h) => ({ title: h.title, kind: h.kind, sourceRef: h.identity.sourceRef, status: h.status, tier: h.tier })),
      };
    }),
    reasoning: {
      kind: reasoning.kind,
      selected: reasoning.selected,
      validated: validateResult(p, INPUT, reasoning),
      tasks: reasoning.tasks.map((t) => ({
        id: t.id,
        sourceRef: t.task?.sourceRef ?? null,
        state: t.state,
        reasons: t.reasons.map((r) => ({ code: r.code, requirement: r.requirement ?? null })),
      })),
    },
  };
}

describe('the shadow view fixture is real cognitive-core output', () => {
  it('the committed fixture equals what search and reasoning produce now', () => {
    const fresh = `${JSON.stringify(build(), null, 2)}\n`;
    if (process.env.SHADOW_FIXTURE_WRITE === '1') writeFileSync(FIXTURE, fresh);
    expect(readFileSync(FIXTURE, 'utf8').replace(/\r\n/g, '\n')).toBe(fresh);
  });

  it('the reasoning result in it passed the independent validator', () => {
    expect(build().reasoning.validated).toBe(true);
  });
});
